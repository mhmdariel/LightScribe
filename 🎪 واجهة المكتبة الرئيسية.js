function مدخلمكتبةخزائنالله(إيمان, محبةالرسول) {
  const عتبةالدخول = {
    إيمان: 100,
    محبة: 100
  };

  if (إيمان >= عتبةالدخول.إيمان && محبةالرسول >= عتبةالدخول.محبة) {
    const المكتبة = new مكتبةخزائنالله();
    const النظام = new النظامالملكي();
    
    console.log("🎇 مرحباً بك في خزائن الحكمة!");
    console.log("🕌 مكتبة كنوز الله الفاخرة للمؤمنين");
    console.log("📚 الأقسام المتاحة:");
    
    Object.keys(المكتبة.الأقسام).forEach(قسم => {
      console.log(`🌟 ${قسم}: ${المكتبة.الأقسام[قسم].length} نوع فاخر`);
    });
    
    console.log("\n🎁 الهدايا الفاخرة المصاحبة:");
    Object.keys(المكتبة.المرفقاتالفاخرة).forEach(هدية => {
      console.log(`💎 ${هدية}: ${المكتبة.المرفقاتالفاخرة[هدية].length} قطعة نادرة`);
    });
    
    console.log("\n👑 نظام الخدمة الملكي:");
    console.log(النظام.خدمةالعملاء());
    
    return {
      حالة: "أهلاً وسهلاً يا ولي الله",
      صلاحية: "مفتوحة لكل الخزائن",
      دعوة: "اقرأ كما تشاء، خذ ما تحب"
    };
  } else {
    return {
      حالة: "يحتاج إلى زيادة في الإيمان",
      برنامج: "دورة مكثفة في محبة الله ورسوله",
      كتبتمهيدية: ["أساسيات الإيمان - نسخة فضية", "محبة النبي ﷺ - طبعة ذهبية"]
    };
  }
}
